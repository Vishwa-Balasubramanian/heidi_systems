import assert from 'node:assert/strict';
import fs from 'node:fs';
import {filterCompanies,sortCompanies} from './dist/logic.mjs';
import {renderContacts} from './dist/contacts.mjs';
const {companies,metrics}=JSON.parse(fs.readFileSync(new URL('./dist/data.json',import.meta.url),'utf8'));
assert.equal(companies.length,292);assert.equal(new Set(companies.map(c=>c.company_id)).size,292);
assert.equal(filterCompanies(companies,{view:'priority'}).length,35);
for(const [priority,count]of [['High Priority',18],['Medium Priority',17],['Needs Research',257]])assert.equal(filterCompanies(companies,{view:'companies',priority}).length,count);
assert.equal(filterCompanies(companies,{q:'xx-no-such-company-xx'}).length,0);
const sample=companies.find(c=>c.domain);assert(filterCompanies(companies,{q:sample.domain.toUpperCase()}).some(c=>c.company_id===sample.company_id));
const units=sortCompanies(companies,'units');const firstUnknown=units.findIndex(c=>c.managed_units==null);assert(units.slice(firstUnknown).every(c=>c.managed_units==null));
assert(filterCompanies(companies,{service:'weg_management',units:'known',completeness:'60'}).every(c=>c.weg_management===true&&c.managed_units!=null&&c.evidence_completeness>=60));
assert.equal(filterCompanies(companies,{status:'AI completed'}).length,metrics.ai_completed);
assert(!fs.readFileSync(new URL('./dist/data.json',import.meta.url),'utf8').includes('OPENAI_API_KEY'));
assert(fs.statSync(new URL('./dist/Heidi_Berlin_AI.xlsx',import.meta.url)).size>10000);
assert.match(renderContacts([]),/No public contact found/);
assert.match(renderContacts([{contact_name:'Test',directory_email:'info@example.org',telephone:'03012345'}]),/mailto:info%40example.org/);
assert.match(renderContacts([{telephone:'03012345'}]),/tel:03012345/);
assert.match(renderContacts([{directory_email:'info@example.org'}]),/Public directory email · unverified/);
assert(!renderContacts([{contact_name:'<script>alert(1)</script>'}]).includes('<script>'));
assert(!renderContacts([{contact_name:'Example',contact_source:'javascript:alert(1)'}]).includes('href="javascript:'));
console.log('Passed: counts, unique IDs, priority views, search, filters, null sorting, status, downloads and allowlist.');
